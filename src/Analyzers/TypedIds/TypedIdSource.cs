namespace YAF.Analyzers.TypedIds;

/// <summary>Writes the generated part of one typed id (02 §3). Every type name is fully qualified, so no using of the consumer matters.</summary>
internal static class TypedIdSource
{
    /// <summary>Returns the source of the generated part of <paramref name="id"/>.</summary>
    /// <param name="id">The id to generate.</param>
    /// <returns>A complete C# file, marked as generated.</returns>
    public static string Write(TypedIdModel id)
    {
        var namespaceLine = id.Namespace is null ? string.Empty : $"namespace {id.Namespace};";
        var name = id.Name;
        return $$"""
            // <auto-generated/>
            #nullable enable

            {{namespaceLine}}

            [global::System.Text.Json.Serialization.JsonConverter(typeof({{name}}.TypedIdJsonConverter))]
            [global::System.ComponentModel.TypeConverter(typeof({{name}}.TypedIdTypeConverter))]
            readonly partial record struct {{name}} : global::YAF.Core.Ids.ITypedId<{{name}}>, global::System.IParsable<{{name}}>
            {
                private {{name}}(global::System.Guid value) => Value = value;

                /// <summary>Gets the wrapped value. Ids created by <see cref="New"/> use a version 7 UUID.</summary>
                public global::System.Guid Value { get; }

                /// <summary>Creates a new id from a version 7 UUID.</summary>
                /// <returns>A new id, never <see langword="default"/>.</returns>
                public static {{name}} New() => new(global::System.Guid.CreateVersion7());

                /// <summary>Creates the id that wraps <paramref name="value"/>, for an id that was created before.</summary>
                /// <param name="value">The wrapped value, as read from a store or a message.</param>
                /// <returns>The id whose <see cref="Value"/> is <paramref name="value"/>.</returns>
                public static {{name}} From(global::System.Guid value) => new(value);

                /// <summary>Parses the text of a guid into an id.</summary>
                /// <param name="s">The text to parse, as <see cref="ToString"/> writes it.</param>
                /// <param name="provider">Ignored, as by <see cref="global::System.Guid"/>.</param>
                /// <returns>The id.</returns>
                /// <exception cref="global::System.FormatException"><paramref name="s"/> is not a guid.</exception>
                public static {{name}} Parse(string s, global::System.IFormatProvider? provider) => new(global::System.Guid.Parse(s, provider));

                /// <summary>Tries to parse the text of a guid into an id.</summary>
                /// <param name="s">The text to parse, as <see cref="ToString"/> writes it.</param>
                /// <param name="provider">Ignored, as by <see cref="global::System.Guid"/>.</param>
                /// <param name="result">The id, or <see langword="default"/> when <paramref name="s"/> is not a guid.</param>
                /// <returns><see langword="true"/> when <paramref name="s"/> is a guid.</returns>
                public static bool TryParse(
                    [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] string? s,
                    global::System.IFormatProvider? provider,
                    [global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] out {{name}} result)
                {
                    var parsed = global::System.Guid.TryParse(s, provider, out var value);
                    result = new(value);
                    return parsed;
                }

                /// <summary>Returns the wrapped guid in format <c>D</c>.</summary>
                /// <returns>The guid, such as <c>0193a4b5-6c7d-7e8f-9a0b-1c2d3e4f5a6b</c>.</returns>
                public override string ToString() => Value.ToString("D");

                internal sealed class TypedIdJsonConverter : global::System.Text.Json.Serialization.JsonConverter<{{name}}>
                {
                    public override {{name}} Read(
                        ref global::System.Text.Json.Utf8JsonReader reader,
                        global::System.Type typeToConvert,
                        global::System.Text.Json.JsonSerializerOptions options) => new(reader.GetGuid());

                    public override void Write(
                        global::System.Text.Json.Utf8JsonWriter writer,
                        {{name}} value,
                        global::System.Text.Json.JsonSerializerOptions options) => writer.WriteStringValue(value.Value);
                }

                internal sealed class TypedIdTypeConverter : global::System.ComponentModel.TypeConverter
                {
                    public override bool CanConvertFrom(global::System.ComponentModel.ITypeDescriptorContext? context, global::System.Type sourceType) =>
                        sourceType == typeof(string) || base.CanConvertFrom(context, sourceType);

                    public override object? ConvertFrom(
                        global::System.ComponentModel.ITypeDescriptorContext? context,
                        global::System.Globalization.CultureInfo? culture,
                        object value) =>
                        value is string text ? Parse(text, culture) : base.ConvertFrom(context, culture, value);
                }
            }

            """;
    }
}
