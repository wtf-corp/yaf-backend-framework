using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace YAF.Analyzers.ErrorCodes;

/// <summary>
/// Emits, in a compilation with a valid <c>YafServiceCode</c> and at least one error catalogue field, the assembly's
/// <c>[assembly: YafService(…)]</c> and the <c>YAF.Generated.YafErrorRegistry</c> it names, which lists every catalogue field in
/// declaration order (03 §2.1), so that the catalogue is read without a scan. The descriptors are read from the fields at run time.
/// A field the registry cannot name (a private catalogue, or one inside a generic type) is left out.
/// </summary>
[Generator(LanguageNames.CSharp)]
internal sealed class ErrorRegistryGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var serviceCode = context.AnalyzerConfigOptionsProvider.Select(
            static (provider, _) => ErrorCodeNaming.ServiceCode(provider.GlobalOptions));

        var fields = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is FieldDeclarationSyntax declaration && declaration.Modifiers.Any(SyntaxKind.StaticKeyword),
                static (syntax, token) => ToFields(syntax, token))
            .SelectMany(static (fields, _) => fields)
            .Collect();

        context.RegisterSourceOutput(fields.Combine(serviceCode), static (output, input) => Emit(output, input.Left, input.Right));
    }

    private static ImmutableArray<CatalogueField> ToFields(GeneratorSyntaxContext syntax, CancellationToken token)
    {
        var declaration = (FieldDeclarationSyntax)syntax.Node;
        var model = syntax.SemanticModel;
        var fields = ImmutableArray.CreateBuilder<CatalogueField>();
        foreach (var variable in declaration.Declaration.Variables)
        {
            if (model.GetDeclaredSymbol(variable, token) is IFieldSymbol { IsStatic: true } field
                && field.Type.ToDisplayString() == ErrorCodeNaming.DescriptorTypeName
                && field.ContainingType.AllInterfaces.Any(static type => type.ToDisplayString() == ErrorCodeNaming.CatalogueTypeName)
                && model.Compilation.IsSymbolAccessibleWithin(field, model.Compilation.Assembly)
                && !IsInGenericType(field.ContainingType))
            {
                fields.Add(new CatalogueField(
                    field.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    FullName(field.ContainingType),
                    field.Name));
            }
        }

        return fields.ToImmutable();
    }

    private static bool IsInGenericType(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.ContainingType)
        {
            if (current.IsGenericType)
            {
                return true;
            }
        }

        return false;
    }

    // The name Type.FullName gives: the namespace, then the containing types outermost first, joined with '+'.
    private static string FullName(INamedTypeSymbol type)
    {
        var name = type.MetadataName;
        for (var outer = type.ContainingType; outer is not null; outer = outer.ContainingType)
        {
            name = outer.MetadataName + "+" + name;
        }

        return type.ContainingNamespace.IsGlobalNamespace ? name : type.ContainingNamespace.ToDisplayString() + "." + name;
    }

    private static void Emit(SourceProductionContext output, ImmutableArray<CatalogueField> fields, string? serviceCode)
    {
        if (fields.IsEmpty || serviceCode is null || !ErrorCodeNaming.IsValidServiceCode(serviceCode))
        {
            return;
        }

        var entries = new StringBuilder();
        foreach (var field in fields)
        {
            entries.Append("                new global::YAF.Core.Results.ErrorRegistration(")
                .Append(field.TypeExpression).Append('.').Append(field.Name).Append(", ")
                .Append(SymbolDisplay.FormatLiteral(field.FullName, quote: true)).Append(", ")
                .Append(SymbolDisplay.FormatLiteral(field.Name, quote: true)).AppendLine("),");
        }

        output.AddSource("YAF.ErrorRegistry.g.cs", $$"""
            // <auto-generated/>
            #nullable enable
            [assembly: global::YAF.Core.Results.YafService({{SymbolDisplay.FormatLiteral(serviceCode, quote: true)}}, typeof(global::YAF.Generated.YafErrorRegistry))]

            namespace YAF.Generated
            {
                internal sealed class YafErrorRegistry : global::YAF.Core.Results.IErrorRegistry
                {
                    public global::System.Collections.Generic.IReadOnlyList<global::YAF.Core.Results.ErrorRegistration> Errors { get; } =
                        new global::YAF.Core.Results.ErrorRegistration[]
                        {
            {{entries}}            };
                }
            }

            """);
    }

    private sealed record CatalogueField(string TypeExpression, string FullName, string Name);
}
