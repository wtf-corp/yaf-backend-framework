using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace YAF.Analyzers.ErrorCodes;

/// <summary>
/// Fills the code of each error of an error catalogue at compile time with one interceptor per factory call (03 §2): the default code
/// <c>&lt;YafServiceCode&gt;.&lt;type path&gt;.&lt;field&gt;</c>, or the code of <c>[ErrorCode]</c>. Without a service code the factory throws.
/// </summary>
[Generator(LanguageNames.CSharp)]
internal sealed class ErrorCodeGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var serviceCode = context.AnalyzerConfigOptionsProvider.Select(
            static (provider, _) => provider.GlobalOptions.TryGetValue("build_property.YafServiceCode", out var value)
                && !string.IsNullOrWhiteSpace(value) ? value.Trim() : null);

        var calls = context.SyntaxProvider
            .CreateSyntaxProvider(static (node, _) => IsCandidate(node), static (syntax, token) => ToCall(syntax, token))
            .Where(static call => call is not null)
            .Collect();

        context.RegisterSourceOutput(calls.Combine(serviceCode), static (output, input) => Emit(output, input.Left!, input.Right));
    }

    private static bool IsCandidate(SyntaxNode node) =>
        node is InvocationExpressionSyntax { Parent: EqualsValueClauseSyntax { Parent: VariableDeclaratorSyntax } } invocation
        && FactoryName(invocation) is { } name
        && ErrorCodeNaming.FactoryNames.Contains(name);

    private static string? FactoryName(InvocationExpressionSyntax invocation) => invocation.Expression switch
    {
        MemberAccessExpressionSyntax member => member.Name.Identifier.ValueText,
        SimpleNameSyntax simple => simple.Identifier.ValueText,
        _ => null,
    };

    private static ErrorFactoryCall? ToCall(GeneratorSyntaxContext syntax, CancellationToken token)
    {
        var invocation = (InvocationExpressionSyntax)syntax.Node;
        var model = syntax.SemanticModel;
        if (model.GetSymbolInfo(invocation, token).Symbol is not IMethodSymbol { IsStatic: true } method
            || method.ContainingType.ToDisplayString() != ErrorCodeNaming.ErrorTypeName
            || model.GetDeclaredSymbol(invocation.Parent!.Parent!, token) is not IFieldSymbol { IsStatic: true } field
            || !field.ContainingType.AllInterfaces.Any(static type => type.ToDisplayString() == ErrorCodeNaming.CatalogueTypeName)
            || model.GetInterceptableLocation(invocation, token) is not { } location)
        {
            return null;
        }

        return new ErrorFactoryCall(
            method.Name,
            ErrorCodeNaming.ExplicitCode(field),
            ErrorCodeNaming.DefaultPath(field),
            location.Version,
            location.Data,
            location.GetDisplayLocation());
    }

    private static void Emit(SourceProductionContext output, ImmutableArray<ErrorFactoryCall?> calls, string? serviceCode)
    {
        var source = new StringBuilder();
        var count = 0;
        foreach (var call in calls.Where(call => call!.ExplicitCode is not null || serviceCode is not null))
        {
            var code = call!.ExplicitCode ?? serviceCode + "." + call.DefaultPath;
            source.Append("        // ").AppendLine(call.DisplayLocation)
                .Append("        [global::System.Runtime.CompilerServices.InterceptsLocation(")
                .Append(call.LocationVersion.ToString(CultureInfo.InvariantCulture)).Append(", ")
                .Append(SymbolDisplay.FormatLiteral(call.LocationData, quote: true)).AppendLine(")]")
                .Append("        public static global::YAF.Core.Results.ErrorDescriptor Intercept")
                .Append(count.ToString(CultureInfo.InvariantCulture)).AppendLine("(string messageTemplate)")
                .Append("            => new global::YAF.Core.Results.ErrorDescriptor(")
                .Append(SymbolDisplay.FormatLiteral(code, quote: true))
                .Append(", global::YAF.Core.Results.ErrorKind.").Append(call.Kind).AppendLine(", messageTemplate);")
                .AppendLine();
            count++;
        }

        if (count > 0)
        {
            output.AddSource("YAF.ErrorCodes.g.cs", Wrap(source.ToString()));
        }
    }

    private static string Wrap(string interceptors) => $$"""
        // <auto-generated/>
        namespace YAF.Generated
        {
            file static class ErrorCodeInterceptors
            {
        {{interceptors}}    }
        }

        namespace System.Runtime.CompilerServices
        {
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]
            file sealed class InterceptsLocationAttribute : global::System.Attribute
            {
                public InterceptsLocationAttribute(int version, string data)
                {
                    _ = version;
                    _ = data;
                }
            }
        }

        """;
}
