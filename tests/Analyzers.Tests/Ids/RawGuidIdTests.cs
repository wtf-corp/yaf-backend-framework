using System.Globalization;
using Microsoft.CodeAnalysis;
using YAF.Analyzers.Ids;
using YAF.Analyzers.TypedIds;

namespace Analyzers.Tests.Ids;

public sealed class RawGuidIdTests
{
    [Fact]
    public async Task PublicMethodGuidSessionId_ReportsYAF1001()
    {
        var source = Snippet("public class", "public void Book(Guid sessionId) { }");

        using var result = await RunAsync(source);

        var diagnostic = result.Diagnostics.Should().ContainSingle().Which;
        diagnostic.Id.Should().Be("YAF1001");
        diagnostic.Severity.Should().Be(DiagnosticSeverity.Warning);
        diagnostic.GetMessage(CultureInfo.InvariantCulture).Should()
            .Be("The parameter 'sessionId' of 'Probe.Sessions.Book(System.Guid)' is a raw Guid; use a typed id");
        Text(diagnostic).Should().Be("sessionId");
    }

    [Fact]
    public async Task ProtectedConstructorNullableGuidNamedId_ReportsYAF1001()
    {
        var source = Snippet("public class", "protected Sessions(Guid? id) { }");

        using var result = await RunAsync(source);

        var diagnostic = result.Diagnostics.Should().ContainSingle().Which;
        diagnostic.Id.Should().Be("YAF1001");
        Text(diagnostic).Should().Be("id");
    }

    [Fact]
    public async Task PublicIndexerGuidSessionId_ReportsYAF1001Once()
    {
        var source = Snippet("public class", "public int this[Guid sessionId] => 0;");

        using var result = await RunAsync(source);

        var diagnostic = result.Diagnostics.Should().ContainSingle().Which;
        diagnostic.Id.Should().Be("YAF1001");
        Text(diagnostic).Should().Be("sessionId");
    }

    [Fact]
    public async Task PrivateMethod_ReportsNothing()
    {
        var source = Snippet("public class", "private void Book(Guid sessionId) { }");

        using var result = await RunAsync(source);

        result.Diagnostics.Should().BeEmpty();
    }

    [Fact]
    public async Task InternalType_ReportsNothing()
    {
        var source = Snippet("internal class", "public void Book(Guid sessionId) { }");

        using var result = await RunAsync(source);

        result.Diagnostics.Should().BeEmpty();
    }

    [Fact]
    public async Task GuidNamedValue_ReportsNothing()
    {
        var source = Snippet("public class", "public void Book(Guid value, Guid valid) { }");

        using var result = await RunAsync(source);

        result.Diagnostics.Should().BeEmpty();
    }

    [Fact]
    public async Task TypedIdFrom_ReportsNothing()
    {
        const string source = """
            using System;
            using YAF.Core.Ids;
            namespace Probe;
            [TypedId]
            public readonly partial record struct SessionId;
            public readonly record struct RoomId : ITypedId<RoomId>
            {
                private RoomId(Guid value) => Value = value;
                public Guid Value { get; }
                public static RoomId From(Guid roomId) => new(roomId);
            }
            """;

        using var result = await RunAsync(source);

        result.Diagnostics.Should().BeEmpty();
    }

    [Fact]
    public async Task GeneratedCode_ReportsNothing()
    {
        var source = "// <auto-generated/>\n" + Snippet("public class", "public void Book(Guid sessionId) { }");

        using var result = await RunAsync(source);

        result.Diagnostics.Should().BeEmpty();
    }

    private static string Snippet(string type, string member) => $$"""
        using System;
        namespace Probe;
        {{type}} Sessions
        {
            {{member}}
        }
        """;

    private static Task<HarnessResult> RunAsync(string source) =>
        GeneratorHarness.RunAsync(source, [new TypedIdGenerator()], [new RawGuidIdAnalyzer()]);

    private static string Text(Diagnostic diagnostic) =>
        diagnostic.Location.SourceTree!.ToString().Substring(diagnostic.Location.SourceSpan.Start, diagnostic.Location.SourceSpan.Length);
}
